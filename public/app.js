const languageSelect = document.getElementById("language");
const districtSelect = document.getElementById("district");

function getLanguage() {
  return languageSelect?.value || "mr";
}

function getText(mr, hi, en) {
  const lang = getLanguage();
  return lang === "en" ? en : lang === "hi" ? hi : mr;
}

function updateToday() {
  const today = document.getElementById("today");
  if (!today) return;

  const locale = getLanguage() === "en"
    ? "en-IN"
    : getLanguage() === "hi" ? "hi-IN" : "mr-IN";

  today.textContent = new Intl.DateTimeFormat(locale, {
    dateStyle: "full"
  }).format(new Date());
}

function updateDistrictMessage() {
  const message = document.getElementById("district-message");
  if (!message || !districtSelect) return;

  const district = districtSelect.selectedOptions[0]?.text || "";

  message.textContent = getText(
    `निवडलेला जिल्हा: ${district}. जिल्हानिहाय Live News पुढील टप्प्यात जोडू.`,
    `चयनित जिला: ${district}। जिले की लाइव खबरें अगले चरण में जोड़ी जाएँगी।`,
    `Selected district: ${district}. Live district news will be connected in the next stage.`
  );
}

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : "mr";
  const dictionary = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  if (districtSelect) {
    const previousValue = districtSelect.value;

    districtSelect.querySelectorAll("option").forEach((option, index) => {
      const translated = districtNames[selectedLanguage]?.[index];
      if (translated) option.textContent = translated;
    });

    districtSelect.value = previousValue;
  }

  try {
    localStorage.setItem("mahaupdate-language", selectedLanguage);
  } catch (error) {
    console.warn("Language preference could not be saved.");
  }

  updateToday();
  updateDistrictMessage();
}

let savedLanguage = "mr";

try {
  savedLanguage = localStorage.getItem("mahaupdate-language") || "mr";
} catch (error) {
  console.warn("Saved language preference is unavailable.");
}

if (languageSelect) {
  languageSelect.value = translations[savedLanguage] ? savedLanguage : "mr";
  applyLanguage(languageSelect.value);

  languageSelect.addEventListener("change", () => {
    applyLanguage(languageSelect.value);
    loadNews();
    loadWeather();
    checkBackend();
  });
}

const yearElement = document.getElementById("year");
if (yearElement) yearElement.textContent = new Date().getFullYear();

if (districtSelect) {
  districtSelect.addEventListener("change", () => {
    updateDistrictMessage();
    loadWeather();
  });
}

async function checkBackend() {
  const status = document.getElementById("news-status");
  if (!status) return;

  try {
    const response = await fetch("/api/health");
    if (!response.ok) throw new Error("Backend request failed");

    const data = await response.json();

    if (data.success) {
      status.textContent = getText(
        "MahaUpdate सर्व्हर कनेक्ट आहे",
        "MahaUpdate सर्वर कनेक्ट है",
        "MahaUpdate server is connected"
      );
    } else {
      status.textContent = getText(
        "सर्व्हर तपासणी आवश्यक",
        "सर्वर की जाँच आवश्यक है",
        "Server check required"
      );
    }
  } catch (error) {
    status.textContent = getText(
      "सर्व्हरशी कनेक्शन होत नाही",
      "सर्वर से कनेक्शन नहीं हो रहा है",
      "Unable to connect to the server"
    );
  }
}

