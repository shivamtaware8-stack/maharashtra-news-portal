async function loadNews() {
  const newsGrid = document.getElementById("news-grid");
  const status = document.getElementById("news-status");

  if (!newsGrid) {
    console.error('News container "#news-grid" was not found in index.html.');
    return;
  }

  const lang = getLanguage();
  const categoryElement = document.getElementById("news-category");
  const category = categoryElement?.value || "all";

  if (status) {
    status.textContent = getText(
      "बातम्या लोड होत आहेत...",
      "खबरें लोड हो रही हैं...",
      "Loading news..."
    );
  }

  newsGrid.replaceChildren();

  try {
    const url =
      "/api/news?category=" + encodeURIComponent(category) +
      "&lang=" + encodeURIComponent(lang);

    const response = await fetch(url);
    if (!response.ok) {
      throw new Error("News API failed: " + response.status);
    }

    const data = await response.json();

    if (!data.success || !Array.isArray(data.news)) {
      throw new Error(data.error || data.message || "Invalid news response");
    }

    if (data.news.length === 0) {
      if (status) status.textContent = getText(
        "या विभागात सध्या बातम्या उपलब्ध नाहीत.",
        "इस श्रेणी में अभी खबरें उपलब्ध नहीं हैं।",
        "No news is currently available in this category."
      );
      return;
    }

    data.news.forEach((item) => {
      const card = document.createElement("article");
      card.className = "news-card";

      const image = document.createElement("div");
      image.className = "card-image news-image";
      image.textContent = "📰";
      image.setAttribute("aria-hidden", "true");

      const content = document.createElement("div");
      content.className = "card-content";

      const tag = document.createElement("span");
      tag.className = "tag";
      tag.textContent = item.source || "Google News";

      const title = document.createElement("h3");
      title.textContent = item.title || getText(
        "शीर्षक उपलब्ध नाही",
        "शीर्षक उपलब्ध नहीं है",
        "Title unavailable"
      );

      content.append(tag, title);

      if (item.publishedAt) {
        const date = new Date(item.publishedAt);

        if (!Number.isNaN(date.getTime())) {
          const dateElement = document.createElement("p");
          dateElement.className = "news-date";

          const locale = lang === "en" ? "en-IN" : lang === "hi" ? "hi-IN" : "mr-IN";
          dateElement.textContent = date.toLocaleString(locale);
          content.append(dateElement);
        }
      }

      if (item.link) {
        const link = document.createElement("a");
        link.href = item.link;
        link.target = "_blank";
        link.rel = "noopener noreferrer";
        link.className = "news-link";
        link.textContent = getText(
          "संपूर्ण बातमी वाचा ↗",
          "पूरी खबर पढ़ें ↗",
          "Read full news ↗"
        );
        content.append(link);
      }

      card.append(image, content);
      newsGrid.append(card);
    });

    if (status) status.textContent = getText(
      `${data.news.length} बातम्या उपलब्ध`,
      `${data.news.length} खबरें उपलब्ध`,
      `${data.news.length} news items loaded`
    );
  } catch (error) {
    console.error("News loading error:", error);

    if (status) status.textContent = getText(
      "बातम्या लोड होऊ शकल्या नाहीत.",
      "खबरें लोड नहीं हो सकीं।",
      "Unable to load news."
    );

    const message = document.createElement("p");
    message.textContent = getText(
      "कृपया सर्व्हर सुरू आहे का ते तपासा आणि पुन्हा प्रयत्न करा.",
      "कृपया जाँचें कि सर्वर चालू है, फिर से प्रयास करें।",
      "Please check that the server is running and try again."
    );
    newsGrid.replaceChildren(message);
  }
}

